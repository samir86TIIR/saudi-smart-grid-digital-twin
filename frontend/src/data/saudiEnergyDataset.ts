/**
 * Deterministic client-side ontology BFS traversal mirroring
 * GET /api/v1/ontology/substations/{id}/blast-radius (ArangoDB graph traversal).
 */
export function computeLocalBlastRadius(
  originNodeId: string,
  nodes: GridSiteNode[],
  edges: EnergyFlowEdge[]
): BlastRadiusResult {
  const nodeMap = new Map(nodes.map((n) => [n.id, n]));
  const origin = nodeMap.get(originNodeId);
  const visitedNodes = new Set<string>([originNodeId]);
  const impactedEdges = new Set<string>();
  const queue: string[] = [originNodeId];

  while (queue.length > 0) {
    const current = queue.shift()!;
    for (const edge of edges) {
      if (edge.sourceId === current) {
        impactedEdges.add(edge.id);
        if (!visitedNodes.has(edge.targetId)) {
          visitedNodes.add(edge.targetId);
          queue.push(edge.targetId);
        }
      }
    }
  }

  const impactedNodeIds = Array.from(visitedNodes);
  let totalMwAtRisk = 0;
  let impactedSmartMeters = 0;
  let criticalAssetsImpacted = 0;

  for (const id of impactedNodeIds) {
    const node = nodeMap.get(id);
    if (!node) continue;
    totalMwAtRisk += node.liveLoadMw;
    impactedSmartMeters += node.smartMeterCount;
    if (node.category === 'critical_asset') {
      criticalAssetsImpacted += 1;
    }
  }

  const cascadingRiskLevel: BlastRadiusResult['cascadingRiskLevel'] =
    totalMwAtRisk >= 800 || criticalAssetsImpacted >= 2
      ? 'SEVERE'
      : totalMwAtRisk >= 350 || criticalAssetsImpacted >= 1
        ? 'HIGH'
        : 'MODERATE';

  const estimatedRecoveryMin =
    cascadingRiskLevel === 'SEVERE' ? 42 : cascadingRiskLevel === 'HIGH' ? 24 : 12;

  return {
    originNodeId,
    originNodeName: origin?.name ?? originNodeId,
    impactedNodeIds,
    impactedEdgeIds: Array.from(impactedEdges),
    totalMwAtRisk: Math.round(totalMwAtRisk),
    impactedSmartMeters,
    criticalAssetsImpacted,
    estimatedRecoveryMin,
    cascadingRiskLevel,
    source: 'demo_replay',
  };
}
